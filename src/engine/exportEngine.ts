import { DEFENSE_MATRIX } from './securityEngine';

export function exportTopologyCsv(nodes: TopologyNode[], links: TopologyLink[]): string {
  let csv = 'Type,ID,Label,Role,IP_Address,MAC_or_DPID,Status,VLAN,Throughput_Mbps\n';
  for (const n of nodes) {
    csv += `Node,"${n.id}","${n.label}","${n.role}","${n.ip}","${n.mac || n.dpid || ''}","${n.status}","${n.vlan || ''}",${n.trafficThroughputMbps || 0}\n`;
  }
  csv += '\nType,Link_ID,Source,Target,Distance_Meters,Delay_ms,Capacity_Mbps,Status,Cost\n';
  for (const l of links) {
    csv += `Link,"${l.id}","${l.source}","${l.target}",${l.distanceMeters},${l.delayMs},${l.capacityMbps},"${l.status}",${l.cost}\n`;
  }
  return csv;
}

export function exportSdnBenchmarkCsv(metrics: DiscoveryProtocolMetrics[]): string {
  let csv = 'Protocol,Packet_Out,Packet_In,Total_Messages,Steady_State_Rate_pps,Controller_CPU_Load,Convergence_Time_ms,Efficiency_Gain_Pct\n';
  for (const m of metrics) {
    csv += `"${m.protocol}",${m.packetOut},${m.packetIn},${m.totalMessages},${m.steadyStateMsgsPerSec},"${m.cpuLoad}",${m.convergenceTimeMs},${m.efficiencyGainPct}\n`;
  }
  return csv;
}

export function exportSecurityMatrixCsv(): string {
  let csv = 'Attack_Vector,Threat_Description,OFDP_Status,OFDP_Acceptance_Pct,Im_OFDP_Defense,Im_OFDP_Acceptance_Pct,sOFTDP_Defense,sOFTDP_Acceptance_Pct\n';
  for (const row of DEFENSE_MATRIX) {
    csv += `"${row.attackType}","${row.threatDescription}","${row.ofdpVulnerability}",${row.ofdpAcceptancePct},"${row.imOfdpDefense}",${row.imOfdpAcceptancePct},"${row.softdpDefense}",${row.softdpAcceptancePct}\n`;
  }
  return csv;
}

